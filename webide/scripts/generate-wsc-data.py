"""
Generates lsp/workshopCodes/data.json from a workshop.codes checkout (https://github.com/netux/workshop.codes,
MIT License, Copyright (c) 2019 Mitchel Jager): the data used by workshop.codes' editor syntax, i.e. the
parameter names and defaults of the workshop functions (parameter objects) and the values of the workshop
constants (@each). Mirrors parseKeywords() in app/javascript/src/components/editor/Editor.svelte.

Usage: python scripts/generate-wsc-data.py <path to workshop.codes>   (requires PyYAML)
"""

import json
import re
import sys
from pathlib import Path

import yaml


def to_capitalize(text: str) -> str:
    # toCapitalize() in app/javascript/src/utils/text.ts
    return re.sub(r"(^\w)|(\s+\w)", lambda match: match.group(0).upper(), text.lower(), flags=re.ASCII)


def js_string(value) -> str:
    # String(value) for the values that YAML can produce here.
    if value is True:
        return "true"
    if value is False:
        return "false"
    return str(value)


def main() -> None:
    wiki = Path(sys.argv[1]) / "config" / "arrays" / "wiki"
    load = lambda name: yaml.safe_load((wiki / name).read_text(encoding="utf-8"))
    defaults = load("defaults.yml")
    lowercase_defaults = [key.lower() for key in defaults]

    functions = []
    # Same order as the editor's completions: values are found before actions.
    for entry in [*load("values.yml"), *load("actions.yml")]:
        args = entry.get("args") or []
        if not args:
            continue
        keys = [to_capitalize(js_string(arg["name"])) for arg in args]
        parameter_defaults = []
        for arg in args:
            default = js_string(arg["default"]).lower().replace(",", "")
            if default.lower() in lowercase_defaults:
                default_key = to_capitalize(default)
                if default_key not in defaults:
                    raise SystemExit(f"Default '{default_key}' of '{entry['en-US']}' not found in defaults.yml")
                parameter_defaults.append(defaults[default_key])
            else:
                parameter_defaults.append(to_capitalize(default))
        functions.append([entry.get("en-US") or entry["name"], keys, parameter_defaults])

    constants = {name: [value["en-US"] for value in values.values()] for name, values in load("constants.yml").items()}

    output = Path(__file__).resolve().parent.parent / "lsp" / "workshopCodes" / "data.json"
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(
        json.dumps(
            {
                "source": "Generated by scripts/generate-wsc-data.py from workshop.codes (https://github.com/netux/workshop.codes), MIT License, Copyright (c) 2019 Mitchel Jager",
                "functions": functions,
                "constants": constants,
            },
            ensure_ascii=False,
            separators=(",", ":"),
        ),
        encoding="utf-8",
    )
    print(f"Wrote {output}: {len(functions)} functions, {len(constants)} constants")


main()
